// Unified helper mapping all watches from the existing inventory to their respective Swiss watchmaker brand
export function getTimepiecesByBrand(brandName: string): JewelleryItem[] {
  if (!brandName || brandName === 'all') {
    return CATALOG_PRODUCTS;
  }

  const normalized = brandName.toLowerCase().trim();
  const seenImages = new Set<string>();
  const results: JewelleryItem[] = [];

  const addItem = (item: JewelleryItem) => {
    if (!seenImages.has(item.image)) {
      seenImages.add(item.image);
      results.push(item);
    }
  };

  // 1. Prioritize curated brand timepieces if defined
  const curated = CURATED_BRAND_TIMEPIECES[brandName];
  if (curated) {
    curated.forEach(addItem);
  }

  // 2. Match from the 36 Catalog products
  CATALOG_PRODUCTS.forEach((item) => {
    if (
      item.name.toLowerCase().includes(normalized) ||
      (item.brand && item.brand.toLowerCase() === normalized)
    ) {
      addItem({ ...item, brand: brandName });
    }
  });

  // 3. Match from the 9 Portfolio collections
  NINE_CATEGORIES_DATA.forEach((col) => {
    if (col.title.toLowerCase().includes(normalized)) {
      addItem({
        id: `brand-portfolio-${col.id}`,
        name: col.title,
        category: col.categoryKey,
        collection: 'Intemporel Haute Horlogerie',
        description: col.description,
        detailedStory: `${col.description} Calibre: ${col.calibre || 'Certified Swiss Manufacture'}. Available at Route des Jeunes 4bis, Les Acacias, Genève.`,
        metal: col.caseMaterial || 'Precious Metal & Sapphire Crystal',
        gemstoneOrPearl: col.highlightText,
        image: col.image,
        price: 'Price on Request',
        galleryImages: [col.image],
        tags: ['Intemporel', 'Genève', brandName, col.highlightText],
        isFeatured: true,
        brand: brandName,
      });
    }
  });

  // 4. Match from the 44 Gallery Stream items
  [...MARQUEE_ROW_1_LINKS, ...MARQUEE_ROW_2_LINKS].forEach((mItem) => {
    if (mItem.title.toLowerCase().includes(normalized)) {
      addItem({
        id: `brand-gallery-${mItem.id}`,
        name: mItem.title,
        category: 'haute-horlogerie',
        collection: 'Intemporel Genève Curations',
        description: `Verified ${brandName} timepiece curated and authenticated by Intemporel Genève.`,
        detailedStory: `${mItem.title} inspected for timing precision and provenance at our Les Acacias boutique, Route des Jeunes 4bis, Genève.`,
        metal: 'Swiss Manufacture Finishing',
        gemstoneOrPearl: 'Certified Swiss Calibre & Sapphire Crystal',
        image: mItem.image,
        price: 'Price on Request',
        galleryImages: [mItem.image],
        tags: ['Intemporel', 'Genève', brandName],
        isFeatured: false,
        brand: brandName,
      });
    }
  });

  // 5. Match from the 9 Editorial Gallery items
  NINE_GALLERY_ITEMS.forEach((gItem) => {
    if (gItem.title.toLowerCase().includes(normalized)) {
      addItem({
        id: `brand-editorial-${gItem.id}`,
        name: gItem.title,
        category: 'haute-horlogerie',
        collection: 'Intemporel Genève Curations',
        description: gItem.caption,
        detailedStory: `${gItem.caption} Available for private viewing at Route des Jeunes 4bis, Les Acacias, Genève.`,
        metal: '18K Gold & Swiss Steel',
        gemstoneOrPearl: gItem.category,
        image: gItem.image,
        price: 'Price on Request',
        galleryImages: [gItem.image],
        tags: ['Intemporel', 'Genève', brandName],
        isFeatured: true,
        brand: brandName,
      });
    }
  });

  return results;
}

